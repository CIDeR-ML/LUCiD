# direction and energy, on a stub forward
# --------------------------------------------------------------------------------------------

NS = 48
TRUE_DIR = np.array([0.48, 0.36, 0.8]) / np.linalg.norm([0.48, 0.36, 0.8])
TRUE_E = 900.0
_rng = np.random.default_rng(3)
SENSOR_DIR = _rng.standard_normal((NS, 3))
SENSOR_DIR /= np.linalg.norm(SENSOR_DIR, axis=1, keepdims=True)


def _charge(direction, energy):
    """A Cherenkov-ish ring: brightest where the sensor sits near the track direction."""
    return (energy / TRUE_E) * (10.0 * np.exp(3.0 * (SENSOR_DIR @ np.asarray(direction))) + 1.0)


def _stub_pred(track, key):
    th, ph = float(track.theta), float(track.phi)
    d = np.array([np.sin(th) * np.cos(ph), np.sin(th) * np.sin(ph), np.cos(th)])
    return None, None, None, jnp.asarray(_charge(d, float(track.energy)))


def _direction(observed):
    return S.cone_direction(_stub_pred, observed, jnp.asarray([0.5, -0.3, 1.0]), 2.0, TRUE_E,
                            levels=3, initial_div=8, max_angle_deg=90.0, reduction=0.5,
                            rings=4, key=jax.random.PRNGKey(789))


def _angle(a, b):
    return np.degrees(np.arccos(np.clip(np.dot(a, b), -1, 1)))


def test_the_cone_finds_the_direction_the_charge_came_from():
    got = _direction(jnp.asarray(_charge(TRUE_DIR, TRUE_E)))
    assert _angle(got, TRUE_DIR) < 12.0


def test_the_cone_follows_the_data():
    flipped = _direction(jnp.asarray(_charge(-TRUE_DIR, TRUE_E)))
    assert _angle(flipped, TRUE_DIR) > 90.0


def _counting_pred(scored):
    """`_stub_pred` that records each direction it is asked to score."""
    def pred(track, key):
        th, ph = float(track.theta), float(track.phi)
        scored.append(np.array([np.sin(th) * np.cos(ph), np.sin(th) * np.sin(ph), np.cos(th)]))
        return _stub_pred(track, key)
    return pred


def _cone(pred, observed, levels):
    return S.cone_direction(pred, observed, jnp.zeros(3), 0.0, TRUE_E, levels=levels,
                            initial_div=8, max_angle_deg=90.0, reduction=0.5, rings=4,
                            key=jax.random.PRNGKey(0))


def test_level_0_scores_each_direction_once():
    """8 polar angles pole to pole: one direction per pole, 16 azimuths on each of the 6 rings
    between, 98 in all. (A polar x azimuth product puts 16 copies at each pole: 128 forwards.)"""
    scored = []
    _cone(_counting_pred(scored), jnp.asarray(_charge(TRUE_DIR, TRUE_E)), levels=1)
    d = np.array(scored)
    assert len(d) == 2 + 6 * 16
    gap = np.min(np.linalg.norm(d[:, None] - d[None], axis=-1) + 10 * np.eye(len(d)))
    assert gap > 0.1
    assert np.sum(d[:, 2] > 1 - 1e-9) == np.sum(d[:, 2] < -1 + 1e-9) == 1      # one per pole


def test_the_cone_returns_the_best_level_and_keeps_its_incumbent():
    """The charge came from a level-0 direction, so level 0 scores the exact minimum and no cone
    point (all at least 11.25 deg off their axis) can match it. The search must return that
    direction, centre every later cone on it, and never score it again."""
    t, p = np.linspace(0, np.pi, 8)[3], 2 * np.pi * 5 / 16
    d0 = np.array([np.sin(t) * np.cos(p), np.sin(t) * np.sin(p), np.cos(t)])
    scored = []
    got = _cone(_counting_pred(scored), jnp.asarray(_charge(d0, TRUE_E)), levels=3)
    np.testing.assert_allclose(got, d0, atol=1e-12)
    n1, n2 = len(S._cone_points(d0, np.radians(90.0), 4)), len(S._cone_points(d0, np.radians(45.0), 4))
    assert len(scored) == 98 + n1 + n2
    # the level-2 cone is around d0 (rings at 11.25, 22.5, 33.75, 45 deg), not around level 1's best
    off = np.array([_angle(x, d0) for x in scored[-n2:]])
    np.testing.assert_allclose(off, np.round(off / 11.25) * 11.25, atol=1e-4)   # float32 angles
    assert set(np.round(off / 11.25).astype(int)) == {1, 2, 3, 4}


@pytest.mark.parametrize('scale', [1.0, 1.25, 0.625])
def test_the_energy_scan_finds_the_energy_the_charge_came_from(scale):
    """The data's energy is ON the 12.5 %-spaced grid, so the pick must be exactly that point.
    (A 15 % tolerance on an off-grid truth let a neighbouring-bin pick pass.)"""
    grid = TRUE_E * np.linspace(0.5, 1.5, 9)                       # contains 0.625, 1.0, 1.25
    e = S.energy_scan(_stub_pred, jnp.asarray(_charge(TRUE_DIR, scale * TRUE_E)),
                      energies=grid, vertex=np.zeros(3),
                      direction=TRUE_DIR, key=jax.random.PRNGKey(456))
    assert e == pytest.approx(scale * TRUE_E, rel=1e-9)


