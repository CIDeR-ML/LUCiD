def test_seed_vertex_time_recovers_a_point_source():
    """The robust version (bright preselection, inlier grid, GN on inliers) must recover a clean
    point source; the un-robust port put the seed about 15 m off."""
    rng = np.random.default_rng(0)
    th = rng.uniform(0, 2 * np.pi, 3000); zc = rng.uniform(-18, 18, 3000)
    pos = np.column_stack([16.9 * np.cos(th), 16.9 * np.sin(th), zc])
    vtrue, t0true = np.array([5., -3., 7.]), 4.0
    v, t0 = _multilaterate(pos, vtrue, t0true, CylinderVolume(16.9, -18.0, 18.0), rng)
    assert np.linalg.norm(v - vtrue) * 100 < 5.0
    assert abs(t0 - t0true) < 1.0


def _multilaterate(pos, vtrue, t0true, region, rng, vs=0.2167):
    """`seed_vertex_time` at the published recipe on a point source: 40 % of PMTs lit, 0.5 ns
    time jitter."""
    T = t0true + np.linalg.norm(pos - vtrue, axis=1) / vs
    oc = (rng.uniform(size=len(pos)) < 0.4).astype(float) * 3.
    ot = np.where(oc > 0, T + rng.normal(0, 0.5, len(pos)), 0.)
    r = S.SEED_RECIPE
    return S.seed_vertex_time(pos, oc, ot, region=region, speed=vs, vgrid=r.time_vgrid,
                              n_refine=r.time_n_refine, gate=r.time_gate,
                              bright_frac=r.time_bright_frac, q_edge=r.time_q_edge)


def _sphere_sensors(radius, n=2000):
    k = np.arange(n) + 0.5                                       # Fibonacci sphere
    cos_t, phi = 1 - 2 * k / n, np.pi * (1 + 5 ** 0.5) * k
    sin_t = np.sqrt(1 - cos_t ** 2)
    return radius * np.column_stack([sin_t * np.cos(phi), sin_t * np.sin(phi), cos_t])


def _box_sensors(h, n=2000, seed=1):
    """Points on the faces of the box of half-extents ``h``."""
    rng = np.random.default_rng(seed)
    p = rng.uniform(-1, 1, (n, 3)) * h
    axis = rng.integers(0, 3, n)
    p[np.arange(n), axis] = np.sign(rng.uniform(-1, 1, n)) * h[axis]
    return p


@pytest.mark.parametrize('shape', ['sphere', 'box'])
def test_seed_vertex_time_stays_in_the_detector_volume(shape):
    """The light comes from just outside the volume, where the unconstrained solution lies. The
    cylinder around the PMT extent (radius the largest PMT hypot, half-height the largest |z|)
    contains that point, the sphere and the box do not: the seed must be in the volume, on its
    surface near the source."""
    if shape == 'sphere':
        region, pos, vtrue = SphereVolume(6.0), _sphere_sensors(6.0), np.array([4.5, 0.0, 4.5])
    else:
        h = np.array([3.0, 6.0, 2.5])
        region, pos, vtrue = BoxVolume(*h), _box_sensors(h), np.array([3.4, 1.0, 0.0])
    tank_r, tank_z = np.hypot(pos[:, 0], pos[:, 1]).max(), np.abs(pos[:, 2]).max()
    assert np.hypot(*vtrue[:2]) < tank_r and abs(vtrue[2]) < tank_z and not region.contains(vtrue)
    v, _ = _multilaterate(pos, vtrue, 4.0, region, np.random.default_rng(0))
    assert region.scaled(1 + 1e-12).contains(v)                 # inside, to rounding
    assert not region.scaled(1 - 1e-6).contains(v)              # on the surface
    assert np.linalg.norm(v - vtrue) < 1.0


def test_a_recipe_must_be_complete_and_known():
    bad = dataclasses.asdict(S.SEED_RECIPE); del bad['cone_rings']
    with pytest.raises(TypeError, match='cone_rings'):
        S.SeedRecipe(**bad)
    with pytest.raises(TypeError, match='cone_typo'):
        S.SeedRecipe(**dataclasses.asdict(S.SEED_RECIPE), cone_typo=1)


@pytest.mark.parametrize('losses,want', [
    ((100.0, 96.0, 99.0), 0),         # B better by 4 %: inside the 5 % margin, keep A
    ((100.0, 90.0, 99.0), 1),         # B better by 10 %: switch to B
    ((100.0, 94.0, 80.0), 2),         # both decisive, F best
    ((-100.0, -103.0, -99.0), 0),     # negative losses: B by 3 % of |base|, keep A
    ((-100.0, -110.0, -99.0), 1),
])
def test_reconstruct_fits_the_start_the_margin_rule_picks(monkeypatch, losses, want):
    """`reconstruct` executed with the seeder and the fit stubbed: the pre-fit losses are the
    model's, averaged over the fit's own keys, and the start handed to the fit is the one the
    5 % margin rule (prefer A) selects."""
    seeds = {'A': np.full(9, 1.0), 'B': np.full(9, 2.0), 'F': np.full(9, 3.0)}
    seen = {}
    monkeypatch.setattr(S, 'seed_track', lambda *a, key, **k: seen.update(seed_key=key) or seeds)

    def fake_fit(model, oc, ot, start, fit, *, key):
        seen['start'], seen['fit'], seen['fit_key'] = np.asarray(start), fit, key
        return np.asarray(start) + 0.5, {'n_rejected': 0}

    monkeypatch.setattr(S, 'fit_track', fake_fit)
    table = dict(zip((1.0, 2.0, 3.0), losses))
    keys_seen = []

    class Model:
        pred = None

        def loss(self, start, oc, ot, key):
            keys_seen.append(np.asarray(key).tolist())
            return table[float(start[0])]

    fit = dataclasses.replace(FIT_RECIPE, nkeys=2, steps=3)
    theta, info = S.reconstruct(Model(), np.ones(4), np.ones(4),
                                seed=dataclasses.replace(S.SEED_RECIPE, pick_margin=0.05),
                                fit=fit, seed_key=jax.random.PRNGKey(11),
                                fit_key=jax.random.PRNGKey(7))
    np.testing.assert_array_equal(seen['seed_key'], jax.random.PRNGKey(11))
    np.testing.assert_array_equal(seen['fit_key'], jax.random.PRNGKey(7))
    assert info['which'] == want
    np.testing.assert_array_equal(seen['start'], seeds['ABF'[want]])
    np.testing.assert_array_equal(theta, seeds['ABF'[want]] + 0.5)
    assert info['losses'] == list(losses)
    assert seen['fit'] is fit
    # each start scored on the fit's keys, split from the event's fit key
    want_keys = np.asarray(jax.random.split(jax.random.PRNGKey(7), 2)).tolist()
    assert keys_seen == want_keys * 3


