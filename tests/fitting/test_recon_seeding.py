def test_the_seeder_takes_the_events_key_and_no_fixed_one():
    for fn, name in ((S.seed_track, 'key'), (S.reconstruct, 'seed_key'), (S.reconstruct, 'fit_key')):
        p = inspect.signature(fn).parameters[name]
        assert p.kind is p.KEYWORD_ONLY and p.default is p.empty, (fn.__name__, name)
    assert not [f.name for f in dataclasses.fields(S.SeedRecipe) if 'key' in f.name]


def _seeding_keys(monkeypatch, key):
    """The keys `seed_track` hands the energy scan and the two cone searches, in call order."""
    got = []
    monkeypatch.setattr(S, 'energy_scan', lambda *a, key, **k: got.append(key) or TRUE_E)
    monkeypatch.setattr(S, 'first_light_grid', lambda *a, **k: (np.zeros(3), 0.0))
    monkeypatch.setattr(S, 'seed_vertex_time', lambda *a, **k: (np.ones(3), 1.0))
    monkeypatch.setattr(S, 'cone_direction', lambda *a, key, **k: got.append(key) or TRUE_DIR)
    det = types.SimpleNamespace(all_points=SENSORS, volume=TANK, S_radius=PMT_R)
    pred = types.SimpleNamespace(det_geom=types.SimpleNamespace(detector=det, speed_of_light=C))
    S.seed_track(pred, CHARGE, TIMES, recipe=S.SEED_RECIPE, key=key)
    return [tuple(np.asarray(k).tolist()) for k in got]


def test_the_energy_scan_and_each_cone_search_draw_their_own_stream(monkeypatch):
    """One key per event, split into three independent streams: the cone searches at A and at B
    no longer share one, and nothing is the same for every event."""
    k = _seeding_keys(monkeypatch, jax.random.PRNGKey(3))
    assert len(k) == 3 and len(set(k)) == 3                          # energy, cone A, cone B
    assert _seeding_keys(monkeypatch, jax.random.PRNGKey(3)) == k    # the same event, the same keys
    assert not set(_seeding_keys(monkeypatch, jax.random.PRNGKey(4))) & set(k)   # another event
