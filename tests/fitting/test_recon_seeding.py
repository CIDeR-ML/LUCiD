"""The seeders in `lucid.fitting.seed`: do they find the answer, from the data alone.

The first-light grid is a closure on noiseless arrival times generated by the model
`grid_origin_time_loss` inverts (straight-line flight at a known speed), with tolerances set at
what the search reaches. The direction and energy seeders need only
``pred(track, key) -> (log_w, times, indices, total_charge)``, so a closed-form charge pattern
peaked at a known direction stands in for the photon forward. None of this needs a detector or
a simulator.

No seeder takes the truth as an argument (`test_no_seeder_is_handed_the_truth`): a seeder that
reads its own answer key is an oracle, and nothing downstream could tell.
"""
import dataclasses
import inspect
import types

import numpy as np
import jax
import jax.numpy as jnp
import pytest

from lucid.fitting import FIT_RECIPE, seed as S
from lucid.geometry.volume import BoxVolume, CylinderVolume, SphereVolume
from lucid.losses import grid_origin_time_loss

C = 0.299792458 / 1.33              # m/ns
PMT_R = 0.25
TANK = CylinderVolume(8.0, -8.0, 8.0)
TRUE_POS = np.array([2.1, -1.4, 3.0])
TRUE_T0 = 4.0


def _sensors(n_phi=16, n_z=7):
    """PMTs on the barrel of the cylinder — enough angular spread to triangulate."""
    phi = np.linspace(0, 2 * np.pi, n_phi, endpoint=False)
    z = np.linspace(-7.0, 7.0, n_z)
    p, zz = np.meshgrid(phi, z, indexing='ij')
    return np.stack([8.0 * np.cos(p).ravel(), 8.0 * np.sin(p).ravel(), zz.ravel()], axis=1)


def _arrivals(pos, t0, sensors):
    """Noiseless direct light: t = t0 + (d - r_pmt)/c, the model the loss inverts."""
    d = np.linalg.norm(sensors - np.asarray(pos)[None, :], axis=1)
    return t0 + (d - PMT_R) / C


SENSORS = _sensors()
TIMES = _arrivals(TRUE_POS, TRUE_T0, SENSORS)
CHARGE = np.ones(len(SENSORS))       # all sensors lit; the loss masks on charge > 0
T0_VALUES = np.linspace(-2.0, 10.0, 7)
T0_STEP = T0_VALUES[1] - T0_VALUES[0]                                          # 2.0 ns


def _grid(times=TIMES, region=TANK.scaled(0.9)):
    return S.first_light_grid(jnp.asarray(SENSORS), jnp.asarray(CHARGE), jnp.asarray(times),
                              region=region, t0_values=T0_VALUES, n_div=5, levels=4,
                              sensor_radius=PMT_R, light_speed=C, early_penalty=100.0)


def _loss(pos, t0):
    return float(grid_origin_time_loss(jnp.asarray(pos), jnp.asarray(SENSORS),
                                       jnp.asarray(TIMES), jnp.asarray(CHARGE), t0,
                                       sensor_radius=PMT_R, light_speed=C, early_penalty=100.0))


def test_no_seeder_is_handed_the_truth():
    for fn in (S.energy_scan, S.first_light_grid, S.seed_vertex_time, S.cone_direction,
               S.fuse_seeds, S.seed_track, S.reconstruct):
        params = inspect.signature(fn).parameters
        assert not [p for p in params if 'true' in p or 'truth' in p], fn.__name__


class TestFirstLightGrid:
    def test_it_recovers_a_synthetic_vertex(self):
        vtx, t0 = _grid()
        assert abs(t0 - TRUE_T0) < 1e-9, 'this vertex should land exactly on the t0 grid'
        assert np.linalg.norm(vtx - TRUE_POS) < 0.10

    def test_a_displaced_vertex_moves_the_seed(self):
        """Vertex and t0 are degenerate along the line of sight, so the tolerance is the distance
        light covers in the t0 offset, plus the on-grid accuracy."""
        other = np.array([-3.0, 2.5, -4.0])
        vtx, t0 = _grid(times=_arrivals(other, TRUE_T0, SENSORS))
        assert np.linalg.norm(vtx - other) < C * abs(t0 - TRUE_T0) + 0.10
        assert abs(t0 - TRUE_T0) <= T0_STEP
        assert np.linalg.norm(vtx - TRUE_POS) > 1.0

    def test_the_seed_stays_inside_the_region(self):
        region = TANK.scaled(0.5)
        vtx, _ = _grid(region=region)
        assert bool(region.contains(vtx))

    @pytest.mark.parametrize('center,half', [((2.9, 0.1, -3.3), 8.0), ((0.3, -1.7, 5.55), 0.9),
                                             ((-1.7, 5.55, -3.3), 0.32), ((0.0, 0.0, 0.0), 1.6)])
    def test_each_grid_axis_has_the_points_its_spacing_implies(self, center, half):
        """A level spans ``center ± half`` at spacing ``2 half / n_div``: n_div + 1 = 6 points per
        axis, ends included. (``arange(c - h, c + h + L, L)`` gave 7 on some axis in every case
        here bar the last, from float overshoot past the end.)"""
        pts = S._grid_points(center, half, 2 * half / 5, BoxVolume(100.0, 100.0, 100.0))
        assert pts.shape == (6 ** 3, 3)
        for axis, c in enumerate(center):
            np.testing.assert_allclose(np.unique(pts[:, axis]), c + half * np.linspace(-1, 1, 6),
                                       rtol=0, atol=1e-12)

    @pytest.mark.parametrize('delta', [0.5, 1.0, 2.0])
    def test_early_light_is_penalised_far_more_heavily_than_late(self, delta):
        """Scattered and reflected photons arrive late, never early, so a hypothesis implying
        early light must cost far more. Posed through t0 at the true vertex: raising t0 drives
        every residual negative, lowering it drives them positive."""
        assert _loss(TRUE_POS, TRUE_T0 + delta) > _loss(TRUE_POS, TRUE_T0 - delta) + 10.0

    def test_the_loss_is_minimised_at_the_truth_among_a_scan(self):
        rng = np.random.default_rng(0)
        cand = np.concatenate([TRUE_POS[None, :], rng.uniform(-6, 6, (60, 3))], axis=0)
        assert int(np.argmin([_loss(c, TRUE_T0) for c in cand])) == 0


