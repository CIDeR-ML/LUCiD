"""Calibrating a detector: one model, one problem, any solver.

::

    model   = CalibrationForward(sim, sources, params)     # what the detector predicts
    data    = closure_data(model, theta_true, gains)        # or the observed (S, n_sensors) charge
    problem = CalibrationProblem(model, data)               # + the estimator and its keys
    res     = calibrate(problem, theta0)                    # the published damped Gauss-Newton
    res     = calibrate(problem, theta0, tx=optax.adam(2e-2))   # ... or any optax rule
    sigma   = crb(model, theta_true)['sigma']               # the bound, from the model alone

Run a closure first on any new detector: data generated by :func:`closure_data` from parameters
you chose, a start perturbed from them, and a fit. It is the only way to tell a broken
configuration from a genuinely hard one, and the truth is known because you set it.

The estimator
-------------
* **Neyman χ²** residual ``(k·M − Q)/√Q``. The weight depends on the data alone. That is not a
  detail — the forward is a Monte-Carlo estimate redrawn every step, so any weight involving the
  model makes the residual nonlinear in it and permanently displaces the fixed point.
* **Profiled gains.** The per-PMT factor is solved in closed form each step (``k = ΣQ/ΣM``,
  see :func:`lucid.fitting.calib.profile_gains` for how that differs from the Neyman minimiser)
  rather than fitted. Order 10^4 nuisance parameters never enter the optimizer.
* **Damped Gauss-Newton** by default (:func:`lucid.fitting.gn.gauss_newton_tx`), on the loop
  reconstruction also runs (:func:`lucid.fitting.minimize.minimize`).
"""
import numpy as np
import jax
import jax.numpy as jnp
import optax

from lucid.fitting.calib import ROLE_TRUTH
from lucid.fitting.gn import gauss_newton_tx
from lucid.fitting.minimize import minimize

__all__ = ['calibrate', 'closure_data']


def calibrate(problem, theta0, *, tx=None, steps=600, refresh=20, max_step=0.5, polyak=50,
              fix=(), scale=None, on_step=None):
    """Fit detector parameters: run ``tx`` on ``problem`` from ``theta0``.

    The defaults are the published calibration recipe.

    Parameters
    ----------
    problem : CalibrationProblem
        The model, the observed charge and the estimator.
    theta0 : array ``(P,)``
        Starting fit vector.
    tx : optax.GradientTransformation or None
        The step rule. ``None`` is the published damped Gauss-Newton,
        ``gauss_newton_tx(lam=0.01, mu=0.1)``; pass ``gauss_newton_tx(lam, mu)`` to change its
        damping. Any optax rule plugs in, e.g. ``optax.adam(2e-2)``: a rule that takes no
        curvature ignores the metric. It is built anyway, because this problem's gradient IS
        ``Jᵀr``, so a first-order rule saves no work here.
    steps : int
    refresh : int
        Rebuild the Jacobian every ``refresh`` steps. The gradient ``Jᵀr`` uses the cached ``J``
        in between, so a larger value makes the search direction stale, not only the metric.
    max_step : float
        Per-component clip on the step; ``0.5`` is +65% in log space.
    polyak : int
        Read out the mean of the last ``polyak`` iterates (0: the last one). The trajectory
        wanders on the Monte-Carlo noise floor rather than settling, so a single iterate is one
        draw from it.
    fix : indices
        Parameters held at their start; the rest are fitted conditional on them.
    scale, on_step
        Passed to :func:`lucid.fitting.minimize.minimize`.

    Returns
    -------
    dict with ``theta`` (fit vector), ``real`` (``params.to_real(theta)``), ``gains`` (the
    profiled per-PMT map at the answer, on step ``steps``'s draw), ``history`` (``steps + 1``
    rows, the start included), ``loss``, ``gnorm``, and ``problem``.
    """
    tx = gauss_newton_tx(lam=0.01, mu=0.1) if tx is None else tx
    res = minimize(problem, jnp.asarray(theta0, dtype=jnp.float32), steps,
                   optax.with_extra_args_support(tx), max_step=max_step, scale=scale,
                   refresh=refresh, readout='polyak' if polyak else 'final', polyak=polyak,
                   fix=fix, on_step=on_step)
    theta = res['theta']
    nuisance = problem.nuisance(jnp.asarray(theta, dtype=jnp.float32), steps)
    return dict(theta=theta, real=problem.forward.params.to_real(theta),
                **{k: np.asarray(v) for k, v in nuisance.items()},
                history=res['history'], loss=res['loss'], gnorm=res['gnorm'], problem=problem)


def closure_data(forward, theta_true, gains=None, *, n_draws=8, seed=0):
    """Pseudo-data: the forward at known parameters, with known per-PMT gains baked in.

    The draws are on ``fold_in(PRNGKey(seed), ROLE_TRUTH)``, a stream no fit draws from
    (:mod:`lucid.fitting.calib`, Keys), whatever the fit's seed.

    ``n_draws`` is not a nicety. The Neyman weight ``1/sqrt(Q)`` is built from the data, so noise
    in the data is noise in the weight. Pass ``1`` to model a single real exposure — but then read
    the answer as one draw, not as a measurement of the estimator.

    The default 8 is the published run's value, not a measured optimum.
    """
    g = jnp.ones(forward.NS) if gains is None else jnp.asarray(gains)
    key = jax.random.fold_in(jax.random.PRNGKey(seed), ROLE_TRUTH)
    return forward.average(jnp.asarray(theta_true, dtype=jnp.float32), key, g, n_draws)
