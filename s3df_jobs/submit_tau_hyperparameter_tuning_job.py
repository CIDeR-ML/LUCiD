def generate_slurm_script(output_dir, n_events, job_name, project_root,
                          partition='ampere', account='mli:cider-ml', time_limit='24:00:00'):
    """Generate SLURM batch script content."""

    output_path = Path(output_dir).resolve()

    # Create log directory
    log_dir = project_root / 's3df_jobs' / 'logs'
    log_dir.mkdir(parents=True, exist_ok=True)

    timestamp = datetime.now().strftime('%Y%m%d_%H%M%S')
    log_file = log_dir / f'{job_name}_{timestamp}.log'
    run_script_file = project_root / 's3df_jobs' / 'generated_scripts' / f'{job_name}_run_{timestamp}.py'

    total_combinations = count_combinations()

    slurm_script = f"""#!/bin/bash
#SBATCH --job-name={job_name}
#SBATCH --output={log_file}
#SBATCH --error={log_file}
#SBATCH --partition={partition}
#SBATCH --account={account}
#SBATCH --nodes=1
#SBATCH --ntasks=1
#SBATCH --cpus-per-task=1
#SBATCH --gpus=1
#SBATCH --mem=39936
#SBATCH --time={time_limit}

echo "=========================================="
echo "TAU_VTX HYPERPARAMETER TUNING"
echo "=========================================="
echo "Job ID: $SLURM_JOB_ID"
echo "Node: $SLURM_NODELIST"
echo "Started: $(date)"
echo "=========================================="
echo ""

cd {project_root}
echo "Working directory: $(pwd)"

export SINGULARITY_IMAGE_PATH=/sdf/group/neutrino/images/develop.sif
function spython() {{
    singularity exec --nv -B /sdf,/fs,/sdf/scratch,/lscratch ${{SINGULARITY_IMAGE_PATH}} python "$@"
}}

echo ""
echo "GPU Information:"
singularity exec --nv -B /sdf,/fs,/sdf/scratch,/lscratch ${{SINGULARITY_IMAGE_PATH}} nvidia-smi
echo ""

echo "=========================================="
echo "Scan Parameters:"
echo "  Output: {output_path}"
echo "  Events per combination: {n_events}"
echo "  Total combinations: {total_combinations}"
echo "  Total events: {total_combinations * n_events}"
echo "=========================================="
echo ""

spython -u {run_script_file} \\
    --output {output_path} \\
    --n-events {n_events}

exit_code=$?

echo ""
echo "=========================================="
echo "Completed: $(date)"
echo "Exit code: $exit_code"
echo "=========================================="

exit $exit_code
"""

    return slurm_script, log_file, run_script_file


def main():
    """Main execution function."""
    args = parse_args()

    project_root = Path(__file__).resolve().parent.parent

    print(f"Script location: {Path(__file__).resolve()}")
    print(f"Project root: {project_root}\n")

    output_path = Path(args.output)
    output_path.mkdir(parents=True, exist_ok=True)

    # Generate scripts
    slurm_script, log_file, run_script_file = generate_slurm_script(
        args.output, args.n_events, args.job_name, project_root,
        args.partition, args.account, args.time
    )

    run_script = generate_run_script(project_root)

    # Save scripts
    timestamp = datetime.now().strftime('%Y%m%d_%H%M%S')
    script_dir = project_root / 's3df_jobs' / 'generated_scripts'
    script_dir.mkdir(parents=True, exist_ok=True)

    slurm_file = script_dir / f'{args.job_name}_{timestamp}.sh'
    with open(slurm_file, 'w') as f:
        f.write(slurm_script)
    slurm_file.chmod(0o755)

    with open(run_script_file, 'w') as f:
        f.write(run_script)
    run_script_file.chmod(0o755)

    total_combinations = count_combinations()

    print(f"{'='*80}")
    print(f"TAU_VTX HYPERPARAMETER TUNING - SLURM Job Generated")
    print(f"{'='*80}")
    print(f"SLURM script: {slurm_file}")
    print(f"Run script: {run_script_file}")
    print(f"Output: {Path(args.output).resolve()}")
    print(f"Log file: {log_file}")
    print(f"Events per combination: {args.n_events}")
    print(f"Time limit: {args.time}")
    print()
    print(f"Scan grid: {total_combinations} combinations")
    for nrays, energy, tau_list in SCAN_GRID:
        print(f"  Nrays={nrays//1000}k, E={energy}MeV: tau={tau_list}")
    print(f"\nTotal events: {total_combinations * args.n_events}")
    print(f"{'='*80}")

    if args.submit:
        print("\nSubmitting job to SLURM...")
        try:
            result = subprocess.run(['sbatch', str(slurm_file)], check=True,
                                     stdout=subprocess.PIPE, stderr=subprocess.PIPE)
            print(f"\n{result.stdout.decode().strip()}")
            print(f"\nMonitor with: squeue -u $USER")
            print(f"View log: tail -f {log_file}")
        except subprocess.CalledProcessError as e:
            print(f"Error submitting job: {e}")
            if e.stderr:
                print(f"STDERR: {e.stderr.decode()}")
            return 1
        except FileNotFoundError:
            print("Error: 'sbatch' command not found.")
            return 1
    else:
        print("\nTo submit this job, run:")
        print(f"  sbatch {slurm_file}")
        print("\nOr re-run with --submit flag")

    return 0


if __name__ == '__main__':
    exit(main())
